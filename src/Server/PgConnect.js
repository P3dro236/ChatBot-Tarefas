import { Pool } from "pg";
import { getEnv } from "../config/env.js";

const SCHEMA_STATEMENTS = Object.freeze([
    `CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        whatsapp_id VARCHAR(100) NOT NULL UNIQUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );`,
    `CREATE TABLE IF NOT EXISTS task (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        titulo VARCHAR(255) NOT NULL,
        materia VARCHAR(255),
        tipo VARCHAR(50) NOT NULL,
        data_entrega DATE,
        observacoes TEXT,
        nota NUMERIC,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );`,
    `DO $$
     BEGIN
         IF EXISTS (
             SELECT 1
             FROM information_schema.columns
             WHERE table_schema = current_schema()
               AND table_name = 'task'
               AND column_name = 'user_task_id'
               AND is_nullable = 'NO'
         ) THEN
             ALTER TABLE task ALTER COLUMN user_task_id DROP NOT NULL;
         END IF;
     END $$;`,
    `DROP INDEX IF EXISTS idx_task_user_task_id;`,
    `DROP INDEX IF EXISTS idx_task_user_id;`,
    `CREATE INDEX IF NOT EXISTS idx_task_user_created_id ON task (user_id, created_at ASC, id ASC);`
]);

let defaultPool = null;

export function createPool(config = {}) {
    const needsEnv =
        config.host === undefined ||
        config.port === undefined ||
        config.user === undefined ||
        config.password === undefined ||
        config.database === undefined;
    const envConfig = needsEnv ? getEnv() : null;

    const dbPool = new Pool({
        host: config.host ?? envConfig.DB_HOST,
        port: config.port ?? envConfig.DB_PORT,
        user: config.user ?? envConfig.DB_USER,
        password: config.password ?? envConfig.DB_PASSWORD,
        database: config.database ?? envConfig.DB_NAME,
        max: config.max ?? 10,
        idleTimeoutMillis: config.idleTimeoutMillis ?? 30000,
        connectionTimeoutMillis: config.connectionTimeoutMillis ?? 5000
    });

    dbPool.on("error", (err) => {
        console.error("Erro inesperado no pool PostgreSQL:", err.message);
    });

    return dbPool;
}

export function getPool() {
    if (!defaultPool) {
        defaultPool = createPool();
    }

    return defaultPool;
}

export async function checkDatabaseConnection(dbPool = getPool()) {
    await dbPool.query("SELECT 1");
    return true;
}

export async function initializeDatabase(dbPool = getPool()) {
    await checkDatabaseConnection(dbPool);

    for (const statement of SCHEMA_STATEMENTS) {
        await dbPool.query(statement);
    }

    return true;
}

export async function closePool(dbPool) {
    if (dbPool) {
        if (dbPool === defaultPool) {
            defaultPool = null;
        }
        await dbPool.end();
        return;
    }

    if (!defaultPool) {
        return;
    }

    const poolToClose = defaultPool;
    defaultPool = null;
    await poolToClose.end();
}
